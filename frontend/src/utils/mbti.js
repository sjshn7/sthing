export function calculateMbti(answers) {
  const count = { E: 0, I: 0, S: 0, N: 0, T: 0, F: 0, J: 0, P: 0 }
  answers.forEach(a => { if (a.value in count) count[a.value]++ })

  const ei = count.E >= count.I ? 'E' : 'I'
  const sn = count.S >= count.N ? 'S' : 'N'
  const tf = count.T >= count.F ? 'T' : 'F'
  const jp = count.J >= count.P ? 'J' : 'P'

  return `${ei}${sn}${tf}${jp}`
}

